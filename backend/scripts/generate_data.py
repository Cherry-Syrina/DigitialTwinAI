def _bmi(weight_kg: float, height_cm: float) -> float:
    m = height_cm / 100.0
    return round(weight_kg / (m * m), 1)


def _parse_hhmm(value: str) -> int:
    h, m = value.split(":")
    return int(h) * 60 + int(m)


