def _glucose_at(
    minutes: np.ndarray,
    bp: dict,
    rng: np.random.Generator,
    noise_state: float,
) -> tuple[np.ndarray, float]:
    """Deterministic-per-call synthetic glucose curve over minute offsets."""
    base = bp["baseline_glucose"]
    dawn = bp["dawn_effect"] * np.exp(-(((minutes % 1440) - 300.0) / 110.0) ** 2)
    circadian = 5.0 * np.sin(2 * np.pi * ((minutes % 1440) / 1440.0 - 0.35))

    glucose = base + dawn + circadian
    # daily meal spikes
    for day_start in range(0, int(minutes.max()) + 1, 1440):
        for meal_offset, amp in ((450, 55.0), (780, 48.0), (1170, 52.0)):
            tm = day_start + meal_offset + float(rng.normal(0, 12))
            dt = minutes - tm
            spike = np.where(
                dt >= 0,
                amp * bp["meal_sensitivity"] * (1 - np.exp(-np.clip(dt, 0, None) / 18.0))
                * np.exp(-np.clip(dt, 0, None) / 105.0),
                0.0,
            )
            glucose = glucose + spike

    # AR(1) noise
    out = np.empty_like(glucose)
    state = noise_state
    for i, g in enumerate(glucose):
        state = 0.82 * state + float(rng.normal(0, 2.4))
        out[i] = g + state
    return out, state


def _sleep_mask(minutes_of_day: np.ndarray, bp: dict) -> np.ndarray:
    start = _parse_hhmm(bp["sleep_window"][0])
    end = _parse_hhmm(bp["sleep_window"][1])
    if start > end:
        return (minutes_of_day >= start) | (minutes_of_day < end)
    return (minutes_of_day >= start) & (minutes_of_day < end)


def build_sensor_readings(
    rng: np.random.Generator,
    start: datetime,
    days: int,
) -> pd.DataFrame:
    freq = pd.date_range(start=start, periods=days * 1440 // INTERVAL, freq=f"{INTERVAL}min")
    rows: list[pd.DataFrame] = []

    for bp in PATIENT_BLUEPRINTS:
        n = len(freq)
        minutes = np.arange(n) * INTERVAL
        glucose, _ = _glucose_at(minutes, bp, rng, noise_state=float(rng.normal(0, 3)))

        # activity: several walking bouts per day
        steps = np.zeros(n, dtype=int)
        for day in range(days):
            bouts = int(rng.integers(2, 5))
            for _ in range(bouts):
                start_idx = int(rng.integers(0, 1440 // INTERVAL - 24))
                idx = day * (1440 // INTERVAL) + start_idx
                length = int(rng.integers(6, 26))
                intensity = int(rng.integers(60, 320))
                steps[idx : idx + length] += intensity

        # exercise reduces glucose slightly with a lag
        activity = pd.Series(steps).rolling(6, min_periods=1).sum().to_numpy()
        glucose = glucose - 0.006 * activity
        glucose = np.clip(glucose, 58.0, 380.0)

        # heart rate
        base = bp["baseline_glucose"]
        hr = (
            64.0
            + 0.05 * (glucose - base)
            + 0.03 * steps
            + 4.0 * np.sin(2 * np.pi * (minutes % 1440) / 1440.0)
            + rng.normal(0, 3.0, n)
        )
        hr = np.clip(hr, 48, 165)

        # sleep
        minutes_of_day = minutes % 1440
        asleep = _sleep_mask(minutes_of_day, bp)
        sleep_minutes = np.where(asleep, float(INTERVAL), 0.0)

        # meals
        meal_event = np.zeros(n, dtype=int)
        for day in range(days):
            for meal_offset in (450, 780, 1170):
                idx = day * (1440 // INTERVAL) + int(round((meal_offset + float(rng.normal(0, 12))) / INTERVAL))
                if 0 <= idx < n:
                    meal_event[idx] = 1
        minutes_since_meal = np.full(n, np.nan)
        last_meal = -10_000
        for i in range(n):
            if meal_event[i] == 1:
                last_meal = i
            minutes_since_meal[i] = (i - last_meal) * INTERVAL
        minutes_since_meal = np.clip(minutes_since_meal, 0, 1440)

        frame = pd.DataFrame(
            {
                "patient_id": bp["patient_id"],
                "timestamp": freq,
                "glucose_mg_dl": np.round(glucose, 1),
                "heart_rate_bpm": np.round(hr, 1),
                "steps_5min": steps,
                "sleep_minutes": sleep_minutes,
                "meal_event": meal_event,
                "minutes_since_meal": minutes_since_meal,
                "data_label": "synthetic",
            }
        )

        # realistic sensor dropouts (contiguous gaps) + missing heart rate
        n_gaps = max(1, days // 2)
        for _ in range(n_gaps):
            gap_start = int(rng.integers(0, n - 4))
            gap_len = int(rng.integers(2, 14))
            frame.loc[frame.index[gap_start : gap_start + gap_len], "glucose_mg_dl"] = np.nan
        hr_missing = rng.random(n) < 0.01
        frame.loc[hr_missing, "heart_rate_bpm"] = np.nan

        rows.append(frame)

    sensor = pd.concat(rows, ignore_index=True)
    sensor["timestamp"] = pd.to_datetime(sensor["timestamp"])
    return sensor


def build_glucose_summaries(
    rng: np.random.Generator,
    sensor: pd.DataFrame,
    profiles: pd.DataFrame,
) -> pd.DataFrame:
    """Previous-period glucose summaries derived from the pre-sensor window only.

    Computed over the first 40% of the sensor window (historical period) and
    used as static context; labels always come from later windows.
    """
    rows = []
    for bp in PATIENT_BLUEPRINTS:
        pid = bp["patient_id"]
        subset = sensor[sensor["patient_id"] == pid]
        split = int(len(subset) * 0.4)
        hist = subset.iloc[:split]
        values = hist["glucose_mg_dl"].dropna().to_numpy()
        if len(values) < 10:
            values = np.array([bp["baseline_glucose"]])
        in_range = ((values >= 70) & (values <= 180)).mean()
        above = (values > 180).mean()
        below = (values < 70).mean()
        end_date = hist["timestamp"].max().date().isoformat() if len(hist) else "2026-09-04"
        rows.append(
            {
                "patient_id": pid,
                "summary_period": "previous_90_days",
                "summary_end_date": end_date,
                "mean_glucose_mg_dl": round(float(values.mean()), 1),
                "std_glucose_mg_dl": round(float(values.std(ddof=0)), 1),
                "time_in_range_pct": round(float(in_range * 100), 1),
                "time_above_range_pct": round(float(above * 100), 1),
                "time_below_range_pct": round(float(below * 100), 1),
                "readings_count": int(len(values)),
                "hba1c_pct": round(
                    float(
                        np.clip(
                            4.8
                            + (values.mean() - 83.0) / 28.5
                            + rng.normal(0, 0.12)
                            + (0.35 if bp["diabetes_type"] == "Type 1" else 0.0),
                            4.8,
                            12.0,
                        )
                    ),
                    1,
                ),
                "data_label": "synthetic",
            }
        )
    return pd.DataFrame(rows)


def validate_dataset(
    profiles: pd.DataFrame,
    ehr: pd.DataFrame,
    summaries: pd.DataFrame,
    sensor: pd.DataFrame,
) -> dict:
    """Raise if generated data violates basic structural expectations."""
    required = {
        "profiles": ["patient_id", "age", "bmi", "years_since_diagnosis"],
        "ehr": ["record_id", "patient_id", "record_date", "hba1c_pct"],
        "summaries": ["patient_id", "hba1c_pct", "summary_end_date"],
        "sensor": [
            "patient_id",
            "timestamp",
            "glucose_mg_dl",
            "heart_rate_bpm",
            "steps_5min",
            "sleep_minutes",
            "meal_event",
            "minutes_since_meal",
        ],
    }
    frames = {"profiles": profiles, "ehr": ehr, "summaries": summaries, "sensor": sensor}
    for name, cols in required.items():
        missing = [c for c in cols if c not in frames[name].columns]
        if missing:
            raise ValueError(f"{name} is missing required columns: {missing}")

    if sensor.duplicated(subset=["patient_id", "timestamp"]).any():
        raise ValueError("sensor readings contain duplicate patient/timestamp rows")
    if not set(profiles["patient_id"]) <= set(sensor["patient_id"]):
        raise ValueError("profile patient ids missing from sensor data")
    if sensor["glucose_mg_dl"].isna().sum() == 0:
        raise ValueError("expected missing values in synthetic sensor glucose column")

    return {
        "patients": int(len(profiles)),
        "ehr_records": int(len(ehr)),
        "summaries": int(len(summaries)),
        "sensor_rows": int(len(sensor)),
        "sensor_missing_glucose": int(sensor["glucose_mg_dl"].isna().sum()),
        "sensor_missing_heart_rate": int(sensor["heart_rate_bpm"].isna().sum()),
    }


def generate(
    out_dir: Path | str = config.DATA_DIR,
    seed: int = config.RANDOM_SEED,
    days: int = 7,
    start: str = "2026-09-01 00:00:00",
) -> dict:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed)

    profiles = build_profiles()
    ehr = build_ehr_records(rng)
    sensor = build_sensor_readings(rng, datetime.fromisoformat(start), days)
    summaries = build_glucose_summaries(rng, sensor, profiles)
    stats = validate_dataset(profiles, ehr, summaries, sensor)

    profiles.to_csv(out / "patient_profiles.csv", index=False)
    ehr.to_csv(out / "ehr_records.csv", index=False)
    summaries.to_csv(out / "glucose_summaries.csv", index=False)
    sensor.to_csv(out / "sensor_readings.csv", index=False)

    manifest = {
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "generator": "glucotwin-ai/scripts/generate_data.py",
        "seed": seed,
        "sample_interval_minutes": INTERVAL,
        "days": days,
        "start": start,
        "data_label": "synthetic",
        "disclaimer": DISCLAIMER,
        "files": [
            "patient_profiles.csv",
            "ehr_records.csv",
            "glucose_summaries.csv",
            "sensor_readings.csv",
        ],
        "stats": stats,
    }
    with open(out / "manifest.json", "w", encoding="utf-8") as fh:
        json.dump(manifest, fh, indent=2)
    return manifest


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate GlucoTwin AI synthetic dataset")
    parser.add_argument("--seed", type=int, default=config.RANDOM_SEED)
    parser.add_argument("--days", type=int, default=7)
    parser.add_argument("--out", type=str, default=str(config.DATA_DIR))
    args = parser.parse_args()
    manifest = generate(out_dir=args.out, seed=args.seed, days=args.days)
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
